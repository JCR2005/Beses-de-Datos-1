
/* 
   UBICACIÓN
 */
CREATE TABLE departamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE municipio (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    departamento_id INTEGER,
    FOREIGN KEY (departamento_id) REFERENCES departamento(id)
);

CREATE TABLE comunidad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    municipio_id INTEGER,
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

/*
   ROLES Y USUARIOS */
CREATE TABLE rol (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    tipo_plaza VARCHAR(10),
    descripcion BLOB SUB_TYPE TEXT
);

CREATE TABLE usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    email VARCHAR(150),
    password_hash VARCHAR(255),
    rol_id INTEGER,
    activo BOOLEAN DEFAULT TRUE,
    CONSTRAINT uq_usuario_email UNIQUE (email),
    FOREIGN KEY (rol_id) REFERENCES rol(id)
);

/* 
   ÁREAS Y EXTENSIONISTAS
 */
CREATE TABLE area (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion BLOB SUB_TYPE TEXT
);

CREATE TABLE extensionista (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER,
    codigo VARCHAR(20),
    area_id INTEGER,
    municipio_id INTEGER,
    CONSTRAINT uq_extensionista_codigo UNIQUE (codigo),
    FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    FOREIGN KEY (area_id) REFERENCES area(id),
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

/* 
   POA Y CAPACITACIONES
 */
CREATE TABLE tema_capacitacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion BLOB SUB_TYPE TEXT,
    area_id INTEGER,
    FOREIGN KEY (area_id) REFERENCES area(id)
);

CREATE TABLE poa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    descripcion BLOB SUB_TYPE TEXT,
    estado VARCHAR(50),
    municipio_id INTEGER,
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

CREATE TABLE capacitacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poa_id INTEGER,
    tema_id INTEGER,
    extensionista_id INTEGER,
    FOREIGN KEY (poa_id) REFERENCES poa(id),
    FOREIGN KEY (tema_id) REFERENCES tema_capacitacion(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

CREATE TABLE meta_mensual (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacitacion_id INTEGER,
    mes INTEGER NOT NULL,
    meta_beneficiarios INTEGER NOT NULL,
    CONSTRAINT chk_meta_mes CHECK (mes BETWEEN 1 AND 12),
    FOREIGN KEY (capacitacion_id) REFERENCES capacitacion(id)
);

CREATE TABLE ejecucion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meta_mensual_id INTEGER,
    beneficiarios_reales INTEGER,
    observaciones BLOB SUB_TYPE TEXT,
    fecha_registro DATE,
    FOREIGN KEY (meta_mensual_id) REFERENCES meta_mensual(id)
);

/* 
   CADER Y PARTICIPANTES
 */
CREATE TABLE participante (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    segundo_apellido VARCHAR(100),
    dpi VARCHAR(20),
    anio_nacimiento INTEGER,
    sexo VARCHAR(1) CHECK (sexo IN ('M', 'F')),
    grupo_etario VARCHAR(10) CHECK (grupo_etario IN ('0-15', '16-49', '50-59', '60-mas')),
    etnia VARCHAR(20) CHECK (etnia IN ('Maya', 'Garifuna', 'Xinca', 'Mestiza', 'Otra')),
    telefono VARCHAR(20),
    hijos INTEGER DEFAULT 0,
    tierra_dispone_hectareas DECIMAL(8,2),
    CONSTRAINT uq_participante_dpi UNIQUE (dpi)
);

CREATE TABLE cader (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    comunidad_id INTEGER,
    promotor_id INTEGER,
    FOREIGN KEY (comunidad_id) REFERENCES comunidad(id),
    FOREIGN KEY (promotor_id) REFERENCES participante(id)
);

CREATE TABLE cader_participante (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cader_id INTEGER,
    participante_id INTEGER,
    activo BOOLEAN DEFAULT TRUE,
    CONSTRAINT uq_cader_participante UNIQUE (cader_id, participante_id),
    FOREIGN KEY (cader_id) REFERENCES cader(id),
    FOREIGN KEY (participante_id) REFERENCES participante(id)
);

CREATE TABLE sesion_capacitacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacitacion_id INTEGER,
    cader_id INTEGER,
    comunidad_id INTEGER,
    fecha DATE NOT NULL,
    subproducto VARCHAR(255),
    descripcion_actividad BLOB SUB_TYPE TEXT,
    FOREIGN KEY (capacitacion_id) REFERENCES capacitacion(id),
    FOREIGN KEY (cader_id) REFERENCES cader(id),
    FOREIGN KEY (comunidad_id) REFERENCES comunidad(id)
);

CREATE TABLE asistencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id INTEGER,
    participante_id INTEGER,
    asistio BOOLEAN DEFAULT TRUE,
    firma_huella BOOLEAN DEFAULT FALSE,
    CONSTRAINT uq_asistencia UNIQUE (sesion_id, participante_id),
    FOREIGN KEY (sesion_id) REFERENCES sesion_capacitacion(id),
    FOREIGN KEY (participante_id) REFERENCES participante(id)
);

/* 
   CULTIVOS Y BENEFICIARIOS
 */
CREATE TABLE tipo_cultivo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE beneficiario_cultivo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participante_id INTEGER,
    tipo_cultivo_id INTEGER,
    area_cultivo_hectareas DECIMAL(8,2),
    FOREIGN KEY (participante_id) REFERENCES participante(id),
    FOREIGN KEY (tipo_cultivo_id) REFERENCES tipo_cultivo(id)
);

/* 
   LLUVIA Y CLIMA
 */
CREATE TABLE tipo_lluvia (
    id INTEGER PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255)
);

CREATE TABLE registro_lluvia_diario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio_id INTEGER,
    anio INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    dia INTEGER NOT NULL,
    lluvia_mm DECIMAL(6,2) DEFAULT 0,
    tipo_lluvia_id INTEGER,
    CONSTRAINT chk_lluvia_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT chk_lluvia_dia CHECK (dia BETWEEN 1 AND 31),
    CONSTRAINT uq_lluvia_diario UNIQUE (municipio_id, anio, mes, dia),
    FOREIGN KEY (municipio_id) REFERENCES municipio(id),
    FOREIGN KEY (tipo_lluvia_id) REFERENCES tipo_lluvia(id)
);

CREATE TABLE decada_lluvia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio_id INTEGER,
    anio INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    decada INTEGER NOT NULL,
    total_lluvia_mm DECIMAL(8,2),
    dias_con_lluvia INTEGER,
    observaciones BLOB SUB_TYPE TEXT,
    CONSTRAINT chk_decada_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT chk_decada_num CHECK (decada BETWEEN 1 AND 3),
    CONSTRAINT uq_decada_lluvia UNIQUE (municipio_id, anio, mes, decada),
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

CREATE TABLE resumen_lluvia_mensual (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio_id INTEGER,
    anio INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    dias_con_lluvia INTEGER DEFAULT 0,
    dias_sin_lluvia INTEGER DEFAULT 0,
    dias_lluvia_menor_5mm INTEGER DEFAULT 0,
    dias_lluvia_mayor_40mm INTEGER DEFAULT 0,
    total_lluvia_mm DECIMAL(8,2) DEFAULT 0,
    CONSTRAINT chk_resumen_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT uq_resumen_mensual UNIQUE (municipio_id, anio, mes),
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

CREATE TABLE daño_cultivo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id INTEGER,
    extensionista_id INTEGER,
    tipo_cultivo_id INTEGER,
    tipo_daño VARCHAR(100),
    descripcion BLOB SUB_TYPE TEXT,
    area_afectada_hectareas DECIMAL(8,2),
    fecha_reporte DATE,
    FOREIGN KEY (comunidad_id) REFERENCES comunidad(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id),
    FOREIGN KEY (tipo_cultivo_id) REFERENCES tipo_cultivo(id)
);

/* 
   ONG Y GANADERÍA
 */
CREATE TABLE ong (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    contacto VARCHAR(100),
    telefono VARCHAR(20),
    municipio_id INTEGER,
    FOREIGN KEY (municipio_id) REFERENCES municipio(id)
);

CREATE TABLE granja (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150),
    propietario VARCHAR(200),
    comunidad_id INTEGER,
    tipo_ganado VARCHAR(100),
    cantidad_cabezas INTEGER,
    FOREIGN KEY (comunidad_id) REFERENCES comunidad(id)
);

CREATE TABLE granja_ong (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    granja_id INTEGER,
    ong_id INTEGER,
    fecha_inicio DATE,
    descripcion BLOB SUB_TYPE TEXT,
    FOREIGN KEY (granja_id) REFERENCES granja(id),
    FOREIGN KEY (ong_id) REFERENCES ong(id)
);

CREATE TABLE actividad_ganadera (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    granja_id INTEGER,
    extensionista_id INTEGER,
    tipo VARCHAR(20) CHECK (tipo IN ('Vacunación', 'Profilaxis', 'Revisión', 'Otro')),
    descripcion BLOB SUB_TYPE TEXT,
    fecha DATE,
    FOREIGN KEY (granja_id) REFERENCES granja(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

CREATE TABLE coordinacion_ong (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ong_id INTEGER,
    extensionista_id INTEGER,
    fecha DATE,
    tipo VARCHAR(100),
    descripcion BLOB SUB_TYPE TEXT,
    resultado BLOB SUB_TYPE TEXT,
    FOREIGN KEY (ong_id) REFERENCES ong(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

/* 
   TRÁMITES
 */
CREATE TABLE tramite_tipo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

CREATE TABLE tramite (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_tipo_id INTEGER,
    extensionista_id INTEGER,
    descripcion BLOB SUB_TYPE TEXT,
    estado VARCHAR(20) CHECK (estado IN ('Pendiente', 'En Gestión', 'Completado', 'Rechazado')),
    fecha_solicitud DATE,
    fecha_resolucion DATE,
    requiere_firma_011 BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (tramite_tipo_id) REFERENCES tramite_tipo(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

/* 
   INSPECCIONES
 */
CREATE TABLE tipo_inspeccion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion BLOB SUB_TYPE TEXT
);

CREATE TABLE inspeccion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extensionista_id INTEGER,
    comunidad_id INTEGER,
    tipo_inspeccion_id INTEGER,
    fecha DATE NOT NULL,
    observaciones BLOB SUB_TYPE TEXT,
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id),
    FOREIGN KEY (comunidad_id) REFERENCES comunidad(id),
    FOREIGN KEY (tipo_inspeccion_id) REFERENCES tipo_inspeccion(id)
);

CREATE TABLE inspeccion_resultado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspeccion_id INTEGER,
    tipo VARCHAR(25) CHECK (tipo IN ('Daño', 'Plaga', 'Prueba Germinación', 'Otro')),
    descripcion BLOB SUB_TYPE TEXT,
    severidad VARCHAR(10) CHECK (severidad IN ('Leve', 'Moderado', 'Severo')),
    accion_recomendada BLOB SUB_TYPE TEXT,
    FOREIGN KEY (inspeccion_id) REFERENCES inspeccion(id)
);

/* 
   SOLICITUDES DE APOYO
 */
CREATE TABLE solicitud_apoyo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cader_id INTEGER,
    extensionista_id INTEGER,
    tipo_apoyo VARCHAR(150),
    descripcion BLOB SUB_TYPE TEXT,
    estado VARCHAR(15) CHECK (estado IN ('Pendiente', 'En Proceso', 'Atendida', 'Rechazada')),
    fecha_solicitud DATE,
    fecha_atencion DATE,
    FOREIGN KEY (cader_id) REFERENCES cader(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

/* 
   LIBRO DE ACTAS
 */
CREATE TABLE acta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_acta VARCHAR(50),
    municipio_id INTEGER,
    extensionista_id INTEGER,
    tipo VARCHAR(100),
    descripcion BLOB SUB_TYPE TEXT,
    fecha DATE NOT NULL,
    firmada BOOLEAN DEFAULT FALSE,
    sellada_011 BOOLEAN DEFAULT FALSE,
    CONSTRAINT uq_acta_numero UNIQUE (numero_acta),
    FOREIGN KEY (municipio_id) REFERENCES municipio(id),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

/* 
   PLANIFICACIONES Y REPORTES
 */
CREATE TABLE planificacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extensionista_id INTEGER,
    tipo VARCHAR(10) CHECK (tipo IN ('Semanal', 'Mensual', 'Anual')),
    fecha_inicio DATE,
    fecha_fin DATE,
    descripcion BLOB SUB_TYPE TEXT,
    archivo_nombre VARCHAR(255),
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

CREATE TABLE reporte (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extensionista_id INTEGER,
    tipo VARCHAR(10) CHECK (tipo IN ('Semanal', 'Mensual', 'Especial')),
    formato VARCHAR(10) CHECK (formato IN ('PDF', 'Word', 'Excel')),
    titulo VARCHAR(200),
    fecha_generacion DATE,
    descripcion BLOB SUB_TYPE TEXT,
    FOREIGN KEY (extensionista_id) REFERENCES extensionista(id)
);

