-- el contador del supertipo sigue despues del mayor id copiado
do $$
begin
    perform setval(pg_get_serial_sequence('personal', 'id_personal'), (select max(id_personal) from personal));
end $$;

-- ============================================================
-- subtipos: comparten la llave del supertipo
-- ============================================================

-- el id del subtipo ya no se genera solo: es el id_personal de la persona
alter table medico alter column id_medico drop identity;
alter table enfermero alter column id_enfermero drop identity;

alter table medico
    add column tipo_personal varchar(9) not null default 'medico',
    -- valida que la fila del subtipo medico apunte a personal de tipo medico
    add constraint ck_medico_tipo_personal check (tipo_personal = 'medico'),
    add constraint fk_medico_personal foreign key (id_medico, tipo_personal)
        references personal(id_personal, tipo_personal)
        on delete cascade on update cascade;

alter table enfermero
    add column tipo_personal varchar(9) not null default 'enfermero',
    -- valida que la fila del subtipo enfermero apunte a personal de tipo enfermero
    add constraint ck_enfermero_tipo_personal check (tipo_personal = 'enfermero'),
    add constraint fk_enfermero_personal foreign key (id_enfermero, tipo_personal)
        references personal(id_personal, tipo_personal)
        on delete cascade on update cascade;

-- ============================================================
-- sincronizacion de los datos comunes
-- ============================================================

-- al guardar un medico, sus datos comunes se toman de PERSONAL
create function fn_medico_desde_personal() returns trigger language plpgsql as $$
declare
    p personal%rowtype;
begin
    select * into p from personal where id_personal = new.id_medico;
    if not found or p.tipo_personal <> 'medico' then
        raise exception 'El médico % debe registrarse primero en personal como medico', new.id_medico;
    end if;
    new.nombres := p.nombres;
    new.apellidos := p.apellidos;
    new.dpi := p.dpi;
    new.telefono := p.telefono;
    new.id_municipio := p.id_municipio;
    new.area := p.area;
    new.id_hospital := p.id_hospital;
    return new;
end $$;

create trigger trg_01_medico_desde_personal before insert or update on medico
    for each row execute function fn_medico_desde_personal();

-- al guardar un enfermero, sus datos comunes se toman de PERSONAL
create function fn_enfermero_desde_personal() returns trigger language plpgsql as $$
declare
    p personal%rowtype;
begin
    select * into p from personal where id_personal = new.id_enfermero;
    if not found or p.tipo_personal <> 'enfermero' then
        raise exception 'El enfermero % debe registrarse primero en personal como enfermero', new.id_enfermero;
    end if;
    new.nombres := p.nombres;
    new.apellidos := p.apellidos;
    new.dpi := p.dpi;
    new.telefono := p.telefono;
    new.id_hospital := p.id_hospital;
    return new;
end $$;

create trigger trg_01_enfermero_desde_personal before insert or update on enfermero
    for each row execute function fn_enfermero_desde_personal();

-- al cambiar PERSONAL, el cambio se replica en su subtipo
create function fn_personal_a_subtipo() returns trigger language plpgsql as $$
begin
    if new.tipo_personal = 'medico' then
        -- el disparador del subtipo vuelve a leer los datos desde personal
        update medico set id_medico = id_medico where id_medico = new.id_personal;
    else
        update enfermero set id_enfermero = id_enfermero where id_enfermero = new.id_personal;
    end if;
    return null;
end $$;

create trigger trg_personal_a_subtipo after update on personal
    for each row execute function fn_personal_a_subtipo();

-- toda persona debe pertenecer a su subtipo (jerarquia completa); se revisa al confirmar
create function fn_personal_completo() returns trigger language plpgsql as $$
begin
    if (new.tipo_personal = 'medico' and not exists (select 1 from medico where id_medico = new.id_personal))
       or (new.tipo_personal = 'enfermero' and not exists (select 1 from enfermero where id_enfermero = new.id_personal)) then
        raise exception 'La persona % (%) no tiene registro en su subtipo', new.id_personal, new.tipo_personal;
    end if;
    return null;
end $$;

create constraint trigger trg_personal_completo after insert on personal
    deferrable initially deferred
    for each row execute function fn_personal_completo();

reset role;
