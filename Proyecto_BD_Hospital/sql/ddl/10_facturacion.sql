-- Proyecto 1 - BD Hospitales de Occidente
-- 10_facturacion.sql : facturas y pagos en cuotas

set search_path to public;

-- metodos con los que se puede pagar una cuota
create table metodo_pago (
    id_metodo_pago integer generated by default as identity primary key,
    nombre varchar(30) not null,
    constraint uq_metodo_pago_nombre unique (nombre)
);

-- factura emitida al terminar el proceso; el paciente y el hospital salen de su origen
create table factura (
    id_factura integer generated by default as identity primary key,
    id_cita integer references cita(id_cita)
        on delete restrict on update cascade,
    id_ingreso integer references ingreso(id_ingreso)
        on delete restrict on update cascade,
    id_cirugia integer references cirugia(id_cirugia)
        on delete restrict on update cascade,
    fecha_emision timestamptz not null,
    descripcion text not null,
    total numeric(10,2) not null,
    numero_cuotas smallint not null default 1,
    constraint uq_factura_cita unique (id_cita),
    constraint uq_factura_ingreso unique (id_ingreso),
    constraint uq_factura_cirugia unique (id_cirugia),
    -- valida que la factura tenga exactamente un origen: cita, ingreso o cirugia
    constraint ck_factura_origen check (num_nonnulls(id_cita, id_ingreso, id_cirugia) = 1),
    -- valida que el monto facturado no sea negativo
    constraint ck_factura_total check (total >= 0),
    -- valida el plan de pago: de 1 a 12 cuotas mensuales
    constraint ck_factura_cuotas check (numero_cuotas between 1 and 12),
    -- valida que la consulta externa se pague en un solo pago en la recepcion del medico
    constraint ck_factura_cita_contado check (id_cita is null or numero_cuotas = 1)
);

-- pago de una cuota de la factura
create table pago (
    id_pago integer generated by default as identity primary key,
    id_factura integer not null references factura(id_factura)
        on delete restrict on update cascade,
    numero_cuota smallint not null,
    monto numeric(10,2) not null,
    fecha_pago date not null,
    id_metodo_pago integer not null references metodo_pago(id_metodo_pago)
        on delete restrict on update cascade,
    -- impide pagar dos veces la misma cuota
    constraint uq_pago_cuota unique (id_factura, numero_cuota),
    -- valida que la cuota sea una de las 12 mensualidades posibles
    constraint ck_pago_cuota check (numero_cuota between 1 and 12),
    -- valida que el monto pagado sea mayor que cero
    constraint ck_pago_monto check (monto > 0)
);
