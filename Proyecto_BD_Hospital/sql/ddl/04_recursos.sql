-- 04_recursos.sql : catalogos de insumos, instrumentos, equipos, medicamentos y diagnosticos

set search_path to public;

-- insumos medicos y quirurgicos con su inventario
create table insumo (
    id_insumo integer generated by default as identity primary key,
    nombre varchar(120) not null,
    descripcion text,
    material varchar(80),
    tipo varchar(10) not null,
    unidad_medida varchar(20) not null,
    costo_unitario numeric(10,2) not null,
    stock_minimo integer not null default 0,
    stock_actual integer not null default 0,
    constraint uq_insumo_nombre unique (nombre),
    -- valida si el insumo es medico, quirurgico u otro
    constraint ck_insumo_tipo check (tipo in ('medico','quirurgico','otro')),
    -- valida que el costo unitario no sea negativo
    constraint ck_insumo_costo check (costo_unitario >= 0),
    -- valida que las cantidades de inventario no sean negativas
    constraint ck_insumo_stock check (stock_minimo >= 0 and stock_actual >= 0)
);

-- instrumental medico y quirurgico
create table instrumento (
    id_instrumento integer generated by default as identity primary key,
    nombre varchar(120) not null,
    descripcion text,
    tipo varchar(10) not null,
    funcion varchar(12) not null,
    estado varchar(16) not null default 'disponible',
    constraint uq_instrumento_nombre unique (nombre),
    -- valida si el instrumento es medico, quirurgico u otro
    constraint ck_instrumento_tipo check (tipo in ('medico','quirurgico','otro')),
    -- valida la funcion del instrumento segun la ficha
    constraint ck_instrumento_funcion check (funcion in ('corte','contencion','hemostatica','retractor','accesorio','implante','otro')),
    -- valida si el instrumento esta disponible, en uso o en mantenimiento
    constraint ck_instrumento_estado check (estado in ('disponible','en_uso','en_mantenimiento'))
);

-- equipos medicos y quirurgicos
create table equipo (
    id_equipo integer generated by default as identity primary key,
    nombre varchar(120) not null,
    descripcion text,
    tipo varchar(10) not null,
    funcion varchar(14) not null,
    estado varchar(16) not null default 'disponible',
    constraint uq_equipo_nombre unique (nombre),
    -- valida si el equipo es medico, quirurgico u otro
    constraint ck_equipo_tipo check (tipo in ('medico','quirurgico','otro')),
    -- valida la funcion del equipo segun la ficha
    constraint ck_equipo_funcion check (funcion in ('exploracion','diagnostico','tratamiento','rehabilitacion','otro')),
    -- valida si el equipo esta disponible, en uso o en mantenimiento
    constraint ck_equipo_estado check (estado in ('disponible','en_uso','en_mantenimiento'))
);

-- medicamentos que se pueden recetar
create table medicamento (
    id_medicamento integer generated by default as identity primary key,
    nombre_generico varchar(80) not null,
    concentracion varchar(30) not null,
    forma_farmaceutica varchar(12) not null,
    -- el mismo medicamento puede venir en varias presentaciones
    constraint uq_medicamento unique (nombre_generico, concentracion, forma_farmaceutica),
    -- valida la presentacion en que se entrega el medicamento
    constraint ck_medicamento_forma check (forma_farmaceutica in ('tableta','capsula','jarabe','suspension','inyectable','crema','gotas','inhalador'))
);

-- diagnosticos segun la clasificacion internacional CIE-10
create table diagnostico (
    id_diagnostico integer generated by default as identity primary key,
    codigo_cie10 varchar(7) not null,
    descripcion varchar(200) not null,
    constraint uq_diagnostico_codigo unique (codigo_cie10),
    -- valida el formato del codigo: letra, dos digitos y subcategoria opcional
    constraint ck_diagnostico_codigo check (codigo_cie10 ~ '^[A-Z][0-9]{2}(\.[0-9]{1,2})?$')
);
