set search_path to public;

-- calificacion de 1 a 5 a un hospital, medico, enfermero o encargado
-- (arco exclusivo: cada fila califica exactamente a uno de los cuatro)
create table calificacion (
    id_calificacion integer generated by default as identity primary key,
    id_paciente integer not null references paciente(id_paciente)
        on delete restrict on update cascade,
    fecha date not null,
    puntuacion smallint not null,
    comentario text,
    id_hospital integer references hospital(id_hospital)
        on delete restrict on update cascade,
    id_medico integer references medico(id_medico)
        on delete restrict on update cascade,
    id_enfermero integer references enfermero(id_enfermero)
        on delete restrict on update cascade,
    id_encargado integer references encargado(id_encargado)
        on delete restrict on update cascade,
    -- atencion que origino la calificacion, cuando fue en consulta externa
    id_consulta integer references consulta(id_consulta)
        on delete restrict on update cascade,
    -- valida la escala de calificacion: 1 la peor, 5 la mejor
    constraint ck_calificacion_puntuacion check (puntuacion between 1 and 5),
    -- valida que se califique exactamente a un hospital, medico, enfermero o encargado
    constraint ck_calificacion_evaluado check (num_nonnulls(id_hospital, id_medico, id_enfermero, id_encargado) = 1)
);
