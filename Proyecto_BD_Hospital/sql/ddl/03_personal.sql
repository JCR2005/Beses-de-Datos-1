-- 03_personal.sql : medicos, enfermeros y turnos de emergencia

set search_path to public;

-- especialidades medicas, clinicas o quirurgicas
create table especialidad (
    id_especialidad integer generated by default as identity primary key,
    nombre varchar(80) not null,
    tipo varchar(10) not null,
    constraint uq_especialidad_nombre unique (nombre),
    -- valida si la especialidad es de atencion clinica o quirurgica
    constraint ck_especialidad_tipo check (tipo in ('clinica','quirurgica'))
);

-- medicos de la cadena (los externos no estan contratados, solo llegan a operar)
create table medico (
    id_medico integer generated by default as identity primary key,
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    dpi char(13) not null,
    telefono varchar(9),
    id_hospital integer not null references hospital(id_hospital)
        on delete restrict on update cascade,
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    area varchar(6) not null,
    id_especialidad integer not null references especialidad(id_especialidad)
        on delete restrict on update cascade,
    tipo_medico varchar(12) not null,
    costo_primera_consulta numeric(10,2),
    horario_inicio time,
    horario_fin time,
    constraint uq_medico_dpi unique (dpi),
    -- valida que el DPI (CUI) tenga 13 digitos
    constraint ck_medico_dpi check (dpi ~ '^[0-9]{13}$'),
    -- valida el telefono de 8 digitos (ej. 5551-2001)
    constraint ck_medico_telefono check (telefono ~ '^[0-9]{4}-?[0-9]{4}$'),
    -- valida si el medico vive en zona urbana o rural
    constraint ck_medico_area check (area in ('Urbana','Rural')),
    -- valida la modalidad del medico dentro del hospital
    constraint ck_medico_tipo check (tipo_medico in ('general','especialista','residente','interno','externo')),
    -- valida que el costo de la primera consulta no sea negativo
    constraint ck_medico_costo check (costo_primera_consulta >= 0),
    -- valida que el horario tenga inicio y fin, o ninguno
    constraint ck_medico_horario_completo check ((horario_inicio is null) = (horario_fin is null)),
    -- valida que la consulta externa sea en turno matutino y termine despues de empezar
    constraint ck_medico_horario check (horario_inicio < horario_fin and horario_fin <= time '13:00'),
    -- valida que un externo no tenga horario ni costo de consulta: solo opera
    constraint ck_medico_externo check (tipo_medico <> 'externo' or (horario_inicio is null and costo_primera_consulta is null))
);

-- enfermeros registrados y practicantes de enfermeria
create table enfermero (
    id_enfermero integer generated by default as identity primary key,
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    dpi char(13) not null,
    telefono varchar(9),
    id_hospital integer not null references hospital(id_hospital)
        on delete restrict on update cascade,
    tipo varchar(12) not null,
    constraint uq_enfermero_dpi unique (dpi),
    -- valida que el DPI (CUI) tenga 13 digitos
    constraint ck_enfermero_dpi check (dpi ~ '^[0-9]{13}$'),
    -- valida el telefono de 8 digitos
    constraint ck_enfermero_telefono check (telefono ~ '^[0-9]{4}-?[0-9]{4}$'),
    -- valida si el enfermero tiene titulo o es practicante
    constraint ck_enfermero_tipo check (tipo in ('registrado','practicante'))
);

-- turnos de 12 horas de la unidad de emergencias (atencion 24/365)
create table turno_emergencia (
    id_turno integer generated by default as identity primary key,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete restrict on update cascade,
    fecha date not null,
    jornada varchar(8) not null,
    -- una unidad tiene un solo turno por jornada cada dia
    constraint uq_turno unique (id_unidad, fecha, jornada),
    -- valida la jornada: diurno 07:00-19:00, nocturno 19:00-07:00
    constraint ck_turno_jornada check (jornada in ('diurno','nocturno'))
);

-- medicos asignados a cada turno de emergencia (asociativa M:N)
create table turno_medico (
    id_turno integer not null references turno_emergencia(id_turno)
        on delete cascade on update cascade,
    id_medico integer not null references medico(id_medico)
        on delete restrict on update cascade,
    primary key (id_turno, id_medico)
);
