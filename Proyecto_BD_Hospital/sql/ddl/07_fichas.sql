-- Proyecto 1 - BD Hospitales de Occidente
-- 07_fichas.sql : fichas de ingreso, egreso y traslado (emergencias, cirugia y hospitalizacion)

set search_path to public;

-- ingreso de un paciente a una unidad; consulta externa no usa esta ficha
create table ingreso (
    id_ingreso integer generated by default as identity primary key,
    id_paciente integer not null references paciente(id_paciente)
        on delete restrict on update cascade,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete restrict on update cascade,
    id_servicio integer references servicio_atencion(id_servicio)
        on delete restrict on update cascade,
    id_medico_encargado integer not null references medico(id_medico)
        on delete restrict on update cascade,
    id_camilla integer references camilla(id_camilla)
        on delete restrict on update cascade,
    id_quirofano integer references quirofano(id_quirofano)
        on delete restrict on update cascade,
    id_turno integer references turno_emergencia(id_turno)
        on delete restrict on update cascade,
    fecha_hora_ingreso timestamptz not null,
    motivo_ingreso text not null,
    diagnostico_presuntivo text,
    prioridad_triage smallint,
    turnos_espera smallint,
    -- valida que se asigne camilla o quirofano, no ambos
    constraint ck_ingreso_ubicacion check (id_camilla is null or id_quirofano is null),
    -- valida la prioridad de atencion: 1 la mas urgente, 5 la menos urgente
    constraint ck_ingreso_prioridad check (prioridad_triage between 1 and 5),
    -- valida que la espera por falta de camilla no sea negativa
    constraint ck_ingreso_espera check (turnos_espera >= 0),
    -- valida que turno, prioridad y espera vayan juntos (solo emergencias los usa)
    constraint ck_ingreso_triage check (num_nulls(id_turno, prioridad_triage, turnos_espera) in (0, 3))
);

-- egreso que cierra un ingreso; unidad, servicio y camilla se obtienen del ingreso
create table egreso (
    id_egreso integer generated by default as identity primary key,
    id_ingreso integer not null references ingreso(id_ingreso)
        on delete restrict on update cascade,
    id_medico integer not null references medico(id_medico)
        on delete restrict on update cascade,
    id_diagnostico_principal integer not null references diagnostico(id_diagnostico)
        on delete restrict on update cascade,
    fecha_hora_egreso timestamptz not null,
    motivo_egreso text not null,
    codigo_egreso varchar(8) not null,
    sin_consentimiento boolean not null default false,
    motivo_sin_consentimiento text,
    codigo_traslado varchar(20),
    referido_otro_hospital boolean not null default false,
    -- un ingreso tiene un solo egreso
    constraint uq_egreso_ingreso unique (id_ingreso),
    -- valida la condicion en que el paciente sale del hospital
    constraint ck_egreso_codigo check (codigo_egreso in ('vivo','muerto','embarazo','parto')),
    -- valida que el egreso sin consentimiento medico explique el motivo, y solo el
    constraint ck_egreso_sin_consentimiento check (sin_consentimiento = (motivo_sin_consentimiento is not null))
);

-- diagnosticos secundarios del egreso (asociativa M:N)
create table egreso_diagnostico (
    id_egreso integer not null references egreso(id_egreso)
        on delete cascade on update cascade,
    id_diagnostico integer not null references diagnostico(id_diagnostico)
        on delete restrict on update cascade,
    primary key (id_egreso, id_diagnostico)
);

-- hospitales y establecimientos fuera de la cadena que reciben traslados
create table institucion_externa (
    id_institucion integer generated by default as identity primary key,
    nombre varchar(120) not null,
    direccion varchar(250) not null,
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    constraint uq_institucion_nombre unique (nombre)
);

-- traslado desde una consulta o un ingreso hacia otra unidad de la red o fuera de ella
create table traslado (
    id_traslado integer generated by default as identity primary key,
    fecha_hora timestamptz not null,
    id_medico_indica integer not null references medico(id_medico)
        on delete restrict on update cascade,
    id_consulta integer references consulta(id_consulta)
        on delete restrict on update cascade,
    id_ingreso integer references ingreso(id_ingreso)
        on delete restrict on update cascade,
    id_unidad_origen integer not null references unidad_medica(id_unidad)
        on delete restrict on update cascade,
    tipo_traslado varchar(7) not null,
    id_unidad_destino integer references unidad_medica(id_unidad)
        on delete restrict on update cascade,
    id_institucion_destino integer references institucion_externa(id_institucion)
        on delete restrict on update cascade,
    -- valida si el traslado es dentro de la red de hospitales o fuera de ella
    constraint ck_traslado_tipo check (tipo_traslado in ('interno','externo')),
    -- valida que el traslado salga de una consulta o de un ingreso, no de ambos
    constraint ck_traslado_origen check (num_nonnulls(id_consulta, id_ingreso) = 1),
    -- valida que el interno vaya a una unidad de la red y el externo a una institucion
    constraint ck_traslado_destino check (
        (tipo_traslado = 'interno' and id_unidad_destino is not null and id_institucion_destino is null)
     or (tipo_traslado = 'externo' and id_institucion_destino is not null and id_unidad_destino is null)
    ),
    -- valida que el traslado no sea hacia la misma unidad
    constraint ck_traslado_unidades check (id_unidad_origen <> id_unidad_destino)
);
