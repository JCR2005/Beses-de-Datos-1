set search_path to public;

-- cita programada con un medico en una clinica de consulta externa
create table cita (
    id_cita integer generated by default as identity primary key,
    id_paciente integer not null references paciente(id_paciente)
        on delete restrict on update cascade,
    id_medico integer not null references medico(id_medico)
        on delete restrict on update cascade,
    fecha_hora timestamptz not null,
    numero_clinica varchar(10) not null,
    medio_asignacion varchar(20) not null,
    estado varchar(12) not null default 'programada',
    es_reconsulta boolean not null default false,
    es_referido boolean not null default false,
    cancelada_sin_aviso boolean not null default false,
    costo_base numeric(10,2) not null,
    costo_final numeric(10,2) not null,
    -- valida por que medio se asigno la cita
    constraint ck_cita_medio check (medio_asignacion in ('telefonico','correo_institucional','recepcion_general','recepcion_medico')),
    -- valida en que situacion se encuentra la cita
    constraint ck_cita_estado check (estado in ('programada','realizada','reprogramada','cancelada')),
    -- valida que solo una cita cancelada pueda marcarse como cancelada sin aviso
    constraint ck_cita_sin_aviso check (not cancelada_sin_aviso or estado = 'cancelada'),
    -- valida que los costos no sean negativos
    constraint ck_cita_costos check (costo_base >= 0 and costo_final >= 0)
);

-- consulta realizada en una cita; paciente, medico y fecha se obtienen de la cita
create table consulta (
    id_consulta integer generated by default as identity primary key,
    id_cita integer not null references cita(id_cita)
        on delete restrict on update cascade,
    id_diagnostico integer not null references diagnostico(id_diagnostico)
        on delete restrict on update cascade,
    otros_datos text,
    notas_observaciones text,
    -- una cita genera a lo sumo una consulta
    constraint uq_consulta_cita unique (id_cita)
);

-- receta entregada al final de la consulta
create table receta (
    id_receta integer generated by default as identity primary key,
    id_consulta integer not null references consulta(id_consulta)
        on delete restrict on update cascade,
    fecha_proxima_cita date,
    -- una consulta genera a lo sumo una receta
    constraint uq_receta_consulta unique (id_consulta)
);

-- medicamentos de cada receta (asociativa M:N)
create table receta_medicamento (
    id_receta integer not null references receta(id_receta)
        on delete cascade on update cascade,
    id_medicamento integer not null references medicamento(id_medicamento)
        on delete restrict on update cascade,
    dosis varchar(80) not null,
    duracion varchar(40) not null,
    primary key (id_receta, id_medicamento)
);
