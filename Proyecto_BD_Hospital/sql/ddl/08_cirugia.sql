-- ============================================================
-- catalogos de cirugia
-- ============================================================

-- tipos de anestesia
create table tipo_anestesia (
    id_tipo_anestesia integer generated by default as identity primary key,
    nombre varchar(40) not null,
    constraint uq_tipo_anestesia_nombre unique (nombre)
);

-- procedimientos quirurgicos que ofrece la red, por especialidad
create table tipo_cirugia (
    id_tipo_cirugia integer generated by default as identity primary key,
    nombre varchar(120) not null,
    id_especialidad integer not null references especialidad(id_especialidad)
        on delete restrict on update cascade,
    constraint uq_tipo_cirugia_nombre unique (nombre)
);

-- aspectos que el enfermero verifica en cada etapa de la cirugia
create table aspecto_quirurgico (
    id_aspecto integer generated by default as identity primary key,
    etapa varchar(15) not null,
    seccion varchar(40) not null,
    nombre varchar(150) not null,
    tipo_evaluacion varchar(13) not null,
    constraint uq_aspecto_nombre unique (seccion, nombre),
    -- valida la etapa del proceso quirurgico
    constraint ck_aspecto_etapa check (etapa in ('preoperatorio','intraoperatorio','postoperatorio')),
    -- valida si el aspecto se califica como exito/falla o por aceptabilidad
    constraint ck_aspecto_evaluacion check (tipo_evaluacion in ('exito_falla','aceptabilidad'))
);

-- rol que cumple cada persona del equipo quirurgico
create table rol_quirurgico (
    id_rol integer generated by default as identity primary key,
    nombre varchar(40) not null,
    tipo_personal varchar(9) not null,
    constraint uq_rol_nombre unique (nombre),
    -- valida si el rol lo cumple un medico o un enfermero
    constraint ck_rol_tipo_personal check (tipo_personal in ('medico','enfermero'))
);

-- ============================================================
-- preoperatorio
-- ============================================================

-- solicitud del cirujano al comite medico para realizar una cirugia
create table agendamiento_quirurgico (
    id_agendamiento integer generated by default as identity primary key,
    id_paciente integer not null references paciente(id_paciente)
        on delete restrict on update cascade,
    id_medico_cirujano integer not null references medico(id_medico)
        on delete restrict on update cascade,
    id_tipo_cirugia integer not null references tipo_cirugia(id_tipo_cirugia)
        on delete restrict on update cascade,
    id_tipo_anestesia integer not null references tipo_anestesia(id_tipo_anestesia)
        on delete restrict on update cascade,
    caracter varchar(10) not null,
    resumen_clinico text not null,
    tiempo_estimado_min smallint not null,
    fecha_hora_solicitud timestamptz not null,
    estado_solicitud varchar(9) not null default 'pendiente',
    motivo_rechazo text,
    id_quirofano_solicitado integer references quirofano(id_quirofano)
        on delete restrict on update cascade,
    fecha_hora_agendada timestamptz,
    -- valida si la cirugia es urgente o programada
    constraint ck_agendamiento_caracter check (caracter in ('urgente','programado')),
    -- valida que el tiempo estimado sea positivo
    constraint ck_agendamiento_tiempo check (tiempo_estimado_min > 0),
    -- valida la decision del comite sobre la solicitud
    constraint ck_agendamiento_estado check (estado_solicitud in ('pendiente','aprobada','rechazada')),
    -- valida que la solicitud rechazada explique el motivo, y solo ella
    constraint ck_agendamiento_rechazo check ((estado_solicitud = 'rechazada') = (motivo_rechazo is not null)),
    -- valida que solo la solicitud aprobada tenga fecha agendada, y que la tenga
    constraint ck_agendamiento_aprobada check ((estado_solicitud = 'aprobada') = (fecha_hora_agendada is not null)),
    -- valida que la cirugia se agende despues de solicitarla
    constraint ck_agendamiento_fechas check (fecha_hora_agendada >= fecha_hora_solicitud)
);

-- insumos que solicita el cirujano (asociativa M:N)
create table requerimiento_insumo (
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete cascade on update cascade,
    id_insumo integer not null references insumo(id_insumo)
        on delete restrict on update cascade,
    cantidad smallint not null,
    primary key (id_agendamiento, id_insumo),
    -- valida que se pida al menos una unidad
    constraint ck_req_insumo_cantidad check (cantidad > 0)
);

-- instrumental que solicita el cirujano (asociativa M:N)
create table requerimiento_instrumento (
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete cascade on update cascade,
    id_instrumento integer not null references instrumento(id_instrumento)
        on delete restrict on update cascade,
    cantidad smallint not null,
    primary key (id_agendamiento, id_instrumento),
    -- valida que se pida al menos una unidad
    constraint ck_req_instrumento_cantidad check (cantidad > 0)
);

-- equipos que solicita el cirujano (asociativa M:N)
create table requerimiento_equipo (
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete cascade on update cascade,
    id_equipo integer not null references equipo(id_equipo)
        on delete restrict on update cascade,
    cantidad smallint not null,
    primary key (id_agendamiento, id_equipo),
    -- valida que se pida al menos una unidad
    constraint ck_req_equipo_cantidad check (cantidad > 0)
);

-- historia clinica: interrogatorio y exploracion fisica del paciente
create table historia_clinica (
    id_historia_clinica integer generated by default as identity primary key,
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete restrict on update cascade,
    id_medico integer not null references medico(id_medico)
        on delete restrict on update cascade,
    fecha date not null,
    fuente_interrogatorio varchar(9) not null,
    religion varchar(40),
    ocupacion varchar(60),
    lugar_nacimiento varchar(80),
    lugar_residencia varchar(80),
    antecedentes_heredofamiliares text not null,
    antecedentes_personales_no_patologicos text not null,
    antecedentes_patologicos text not null,
    padecimiento_actual text not null,
    interrogatorio_aparatos_sistemas text,
    sintomas_generales_terapeutica text,
    estudios_previos text,
    signos_vitales text,
    exploracion_general text,
    exploracion_sistematizada text,
    constraint uq_historia_agendamiento unique (id_agendamiento),
    -- valida si la informacion la dio el paciente o un familiar o amigo
    constraint ck_historia_fuente check (fuente_interrogatorio in ('directo','indirecto'))
);

-- consentimiento informado firmado por el medico y el paciente o su representante
create table consentimiento_informado (
    id_consentimiento integer generated by default as identity primary key,
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete restrict on update cascade,
    id_medico integer not null references medico(id_medico)
        on delete restrict on update cascade,
    procedimiento_nombre varchar(150) not null,
    procedimiento_objetivo text not null,
    procedimiento_caracteristicas text not null,
    procedimiento_riesgos text not null,
    medico_firmo boolean not null default false,
    firmante_nombre varchar(150) not null,
    firmante_relacion varchar(20) not null,
    firmante_firmo boolean not null default false,
    fecha_obtencion date not null,
    constraint uq_consentimiento_agendamiento unique (id_agendamiento),
    -- valida quien firma por el paciente
    constraint ck_consentimiento_firmante check (firmante_relacion in ('paciente','familiar','tutor','representante_legal'))
);

-- evaluacion del riesgo anestesico (clasificacion ASA)
create table chequeo_preanestesico (
    id_chequeo integer generated by default as identity primary key,
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete restrict on update cascade,
    clasificacion_asa varchar(3) not null,
    id_medico_clasifica integer not null references medico(id_medico)
        on delete restrict on update cascade,
    plan_anestesia text not null,
    id_medico_anestesista integer not null references medico(id_medico)
        on delete restrict on update cascade,
    constraint uq_chequeo_agendamiento unique (id_agendamiento),
    -- valida la clasificacion ASA de la American Society of Anesthesiologists
    constraint ck_chequeo_asa check (clasificacion_asa in ('I','II','III','IV','V','VI'))
);

-- ============================================================
-- cirugia
-- ============================================================

-- cirugia realizada a partir de un agendamiento aprobado
create table cirugia (
    id_cirugia integer generated by default as identity primary key,
    id_agendamiento integer not null references agendamiento_quirurgico(id_agendamiento)
        on delete restrict on update cascade,
    id_quirofano integer not null references quirofano(id_quirofano)
        on delete restrict on update cascade,
    id_ingreso integer references ingreso(id_ingreso)
        on delete restrict on update cascade,
    fecha_hora_inicio timestamptz not null,
    fecha_hora_fin timestamptz,
    estado varchar(15) not null default 'preoperatorio',
    condicion_evolucion varchar(21),
    constraint uq_cirugia_agendamiento unique (id_agendamiento),
    -- valida en que fase se encuentra la cirugia
    constraint ck_cirugia_estado check (estado in ('preoperatorio','intraoperatorio','postoperatorio','finalizada')),
    -- valida como evoluciono el paciente durante la cirugia
    constraint ck_cirugia_evolucion check (condicion_evolucion in ('sin_complicaciones','complicaciones','complicaciones_graves')),
    -- valida que la cirugia termine despues de empezar
    constraint ck_cirugia_fechas check (fecha_hora_fin >= fecha_hora_inicio),
    -- valida que la cirugia finalizada tenga hora de fin y condicion de evolucion
    constraint ck_cirugia_finalizada check (estado <> 'finalizada' or (fecha_hora_fin is not null and condicion_evolucion is not null))
);

-- personal que participa en la cirugia: un medico o un enfermero por fila
create table cirugia_personal (
    id_cirugia_personal integer generated by default as identity primary key,
    id_cirugia integer not null references cirugia(id_cirugia)
        on delete cascade on update cascade,
    id_medico integer references medico(id_medico)
        on delete restrict on update cascade,
    id_enfermero integer references enfermero(id_enfermero)
        on delete restrict on update cascade,
    id_rol integer not null references rol_quirurgico(id_rol)
        on delete restrict on update cascade,
    constraint uq_cirugia_medico unique (id_cirugia, id_medico),
    constraint uq_cirugia_enfermero unique (id_cirugia, id_enfermero),
    -- valida que cada fila sea de un medico o de un enfermero, no ambos
    constraint ck_cirugia_personal check (num_nonnulls(id_medico, id_enfermero) = 1)
);

-- resultado de cada aspecto verificado durante la cirugia
create table registro_procedimiento (
    id_registro integer generated by default as identity primary key,
    id_cirugia integer not null references cirugia(id_cirugia)
        on delete cascade on update cascade,
    id_aspecto integer not null references aspecto_quirurgico(id_aspecto)
        on delete restrict on update cascade,
    resultado varchar(22) not null,
    descripcion text,
    fecha_hora_registro timestamptz not null,
    id_enfermero integer not null references enfermero(id_enfermero)
        on delete restrict on update cascade,
    -- cada aspecto se registra una vez por cirugia
    constraint uq_registro_aspecto unique (id_cirugia, id_aspecto),
    -- valida el resultado: exito/falla o nivel de aceptabilidad
    constraint ck_registro_resultado check (resultado in ('exito','falla','aceptable','medianamente_aceptable','no_aceptable'))
);

-- documentacion de cada etapa enviada a secretaria por el enfermero encargado
create table documentacion_etapa (
    id_cirugia integer not null references cirugia(id_cirugia)
        on delete cascade on update cascade,
    etapa varchar(15) not null,
    id_enfermero integer not null references enfermero(id_enfermero)
        on delete restrict on update cascade,
    fecha_envio date not null,
    primary key (id_cirugia, etapa),
    -- valida la etapa del proceso quirurgico
    constraint ck_documentacion_etapa check (etapa in ('preoperatorio','intraoperatorio','postoperatorio'))
);

-- insumos usados en la cirugia, con el costo al momento de usarlos (asociativa M:N)
create table cirugia_insumo (
    id_cirugia integer not null references cirugia(id_cirugia)
        on delete cascade on update cascade,
    id_insumo integer not null references insumo(id_insumo)
        on delete restrict on update cascade,
    cantidad smallint not null,
    costo_unitario numeric(10,2) not null,
    primary key (id_cirugia, id_insumo),
    -- valida que se use al menos una unidad
    constraint ck_cirugia_insumo_cantidad check (cantidad > 0),
    -- valida que el costo unitario no sea negativo
    constraint ck_cirugia_insumo_costo check (costo_unitario >= 0)
);
