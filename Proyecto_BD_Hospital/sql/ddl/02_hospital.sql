-- Proyecto 1 - BD Hospitales de Occidente
-- 02_hospital.sql : hospitales, unidades de atencion e infraestructura

set search_path to public;

-- hospitales de la cadena
create table hospital (
    id_hospital integer generated by default as identity primary key,
    nombre varchar(120) not null,
    informacion_especifica text,
    direccion varchar(250) not null,
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    constraint uq_hospital_nombre unique (nombre)
);

-- las 4 unidades de atencion de cada hospital
create table unidad_medica (
    id_unidad integer generated by default as identity primary key,
    id_hospital integer not null references hospital(id_hospital)
        on delete cascade on update cascade,
    tipo_unidad varchar(20) not null,
    costo_dia_hospitalizacion numeric(10,2),
    -- un hospital tiene una sola unidad de cada tipo
    constraint uq_unidad_tipo unique (id_hospital, tipo_unidad),
    -- valida que la unidad sea una de las 4 unidades de atencion
    constraint ck_unidad_tipo check (tipo_unidad in ('Consulta Externa','Emergencias','Cirugía','Hospitalización')),
    -- valida que el costo por dia no sea negativo
    constraint ck_unidad_costo_dia check (costo_dia_hospitalizacion >= 0),
    -- valida que solo hospitalizacion cobre costo por dia, y que lo tenga
    constraint ck_unidad_costo_hospitalizacion check ((tipo_unidad = 'Hospitalización') = (costo_dia_hospitalizacion is not null))
);

-- tipo de servicio (atencion medica) que ofrece cada unidad, con su costo
create table servicio_atencion (
    id_servicio integer generated by default as identity primary key,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete cascade on update cascade,
    nombre varchar(80) not null,
    costo numeric(10,2) not null,
    constraint uq_servicio_nombre unique (id_unidad, nombre),
    -- valida que el costo del servicio no sea negativo
    constraint ck_servicio_costo check (costo >= 0)
);

-- camillas de emergencias y de hospitalizacion
create table camilla (
    id_camilla integer generated by default as identity primary key,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete cascade on update cascade,
    numero smallint not null,
    disponible boolean not null default true,
    constraint uq_camilla_numero unique (id_unidad, numero),
    -- valida que el numero de camilla sea positivo
    constraint ck_camilla_numero check (numero > 0)
);

-- quirofanos de la unidad de cirugia
create table quirofano (
    id_quirofano integer generated by default as identity primary key,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete cascade on update cascade,
    numero smallint not null,
    estado varchar(16) not null default 'disponible',
    constraint uq_quirofano_numero unique (id_unidad, numero),
    -- valida que el numero de quirofano sea positivo
    constraint ck_quirofano_numero check (numero > 0),
    -- valida si el quirofano esta libre, ocupado o en mantenimiento
    constraint ck_quirofano_estado check (estado in ('disponible','ocupado','en_mantenimiento'))
);
