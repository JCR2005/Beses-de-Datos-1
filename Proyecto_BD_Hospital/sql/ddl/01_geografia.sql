-- 01_geografia.sql : catalogo de departamentos y municipios de Guatemala

set search_path to public;

-- los 22 departamentos del pais
create table departamento (
    id_departamento integer generated by default as identity primary key,
    nombre varchar(80) not null,
    constraint uq_departamento_nombre unique (nombre)
);

-- municipios de cada departamento
create table municipio (
    id_municipio integer generated by default as identity primary key,
    id_departamento integer not null references departamento(id_departamento)
        on delete restrict on update cascade,
    nombre varchar(80) not null,
    -- dos departamentos pueden tener un municipio con el mismo nombre
    constraint uq_municipio_nombre unique (id_departamento, nombre)
);
