-- 05_pacientes.sql : pacientes, encargados y sus catalogos

set search_path to public;

-- catalogo de estados civiles
create table estado_civil (
    id_estado_civil integer generated by default as identity primary key,
    nombre varchar(20) not null,
    constraint uq_estado_civil_nombre unique (nombre)
);

-- catalogo de parentescos entre paciente y encargado
create table parentesco (
    id_parentesco integer generated by default as identity primary key,
    nombre varchar(20) not null,
    constraint uq_parentesco_nombre unique (nombre)
);

-- paciente de la red; la edad no se guarda, se calcula con fn_edad
create table paciente (
    id_paciente integer generated by default as identity primary key,
    numero_expediente varchar(20) not null,
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    fecha_nacimiento date not null,
    sexo varchar(9) not null,
    dpi char(13),
    telefono varchar(9),
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    area varchar(6) not null,
    id_estado_civil integer references estado_civil(id_estado_civil)
        on delete restrict on update cascade,
    numero_seguro_social varchar(30),
    constraint uq_paciente_expediente unique (numero_expediente),
    constraint uq_paciente_dpi unique (dpi),
    -- valida el sexo registrado en la ficha
    constraint ck_paciente_sexo check (sexo in ('Masculino','Femenino')),
    -- valida que el DPI (CUI) tenga 13 digitos; los menores pueden no tenerlo
    constraint ck_paciente_dpi check (dpi ~ '^[0-9]{13}$'),
    -- valida el telefono de 8 digitos
    constraint ck_paciente_telefono check (telefono ~ '^[0-9]{4}-?[0-9]{4}$'),
    -- valida si el paciente vive en zona urbana o rural
    constraint ck_paciente_area check (area in ('Urbana','Rural')),
    -- valida el rango de edad: nadie nacido antes de 1900 (maximo ~120 anos)
    constraint ck_paciente_fecha_nacimiento check (fecha_nacimiento >= date '1900-01-01')
);

-- persona responsable del paciente (no es un paciente)
create table encargado (
    id_encargado integer generated by default as identity primary key,
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    dpi char(13) not null,
    telefono varchar(9),
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    area varchar(6) not null,
    constraint uq_encargado_dpi unique (dpi),
    -- valida que el DPI (CUI) tenga 13 digitos
    constraint ck_encargado_dpi check (dpi ~ '^[0-9]{13}$'),
    -- valida el telefono de 8 digitos
    constraint ck_encargado_telefono check (telefono ~ '^[0-9]{4}-?[0-9]{4}$'),
    -- valida si el encargado vive en zona urbana o rural
    constraint ck_encargado_area check (area in ('Urbana','Rural'))
);

-- encargados de cada paciente con su parentesco (asociativa M:N)
create table paciente_encargado (
    id_paciente integer not null references paciente(id_paciente)
        on delete cascade on update cascade,
    id_encargado integer not null references encargado(id_encargado)
        on delete cascade on update cascade,
    id_parentesco integer not null references parentesco(id_parentesco)
        on delete restrict on update cascade,
    primary key (id_paciente, id_encargado)
);
