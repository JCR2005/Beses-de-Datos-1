-- Proyecto 2 - BD Hospitales de Occidente
-- 01_personal.sql : supertipo PERSONAL con los subtipos MEDICO y ENFERMERO (Bloque B)
--
-- Estrategia: una tabla para el supertipo y una por subtipo, que comparten la
-- llave primaria (id_medico = id_enfermero = id_personal). PERSONAL guarda los
-- datos comunes y el discriminador tipo_personal.
--
-- Migracion no destructiva: medico y enfermero conservan sus columnas del
-- Proyecto 1 (nombres, DPI, hospital...). Al registrar personal nuevo esos
-- datos se guardan en PERSONAL y tambien en su subtipo.
--
-- Se ejecuta con el rol administrativo.

set role admin;

-- ============================================================
-- supertipo
-- ============================================================

-- datos que comparte todo el personal del hospital
create table personal (
    id_personal integer generated by default as identity primary key,
    tipo_personal varchar(9) not null,  --discriminador
    nombres varchar(100) not null,
    apellidos varchar(100) not null,
    dpi char(13) not null,
    telefono varchar(9),
    direccion varchar(250) not null,
    id_municipio integer not null references municipio(id_municipio)
        on delete restrict on update cascade,
    area varchar(6) not null,
    id_hospital integer not null references hospital(id_hospital)
        on delete restrict on update cascade,
    fecha_contratacion date,
    salario numeric(10,2),
    nivel_acceso varchar(13) not null default 'consulta',
    constraint uq_personal_dpi unique (dpi),
    -- permite que cada subtipo referencie la pareja (id, tipo) y no el de otro tipo, osea que verifica que esa pareja id, tipo sea unica
    constraint uq_personal_tipo unique (id_personal, tipo_personal),
    -- valida el discriminador: a que subtipo pertenece la persona
    constraint ck_personal_tipo check (tipo_personal in ('medico','enfermero')),
    -- valida que el DPI (CUI) tenga 13 caracteres
    constraint ck_personal_dpi check (length(dpi) = 13),
    -- valida el telefono: 8 digitos, o 9 si lleva guion (5551-2031)
    constraint ck_personal_telefono check (length(telefono) between 8 and 9),
    -- valida si la persona vive en zona urbana o rural
    constraint ck_personal_area check (area in ('Urbana','Rural')),
    -- valida que la fecha de contratacion sea razonable
    constraint ck_personal_contratacion check (fecha_contratacion >= date '1970-01-01'),
    -- valida que el salario no sea negativo
    constraint ck_personal_salario check (salario >= 0),
    -- valida que solo el personal contratado tenga salario (los externos no)
    constraint ck_personal_contratado check ((fecha_contratacion is null) = (salario is null)),
    -- valida el nivel de acceso al sistema de informacion del hospital
    constraint ck_personal_nivel_acceso check (nivel_acceso in ('consulta','operativo','supervisor','administrador'))
);

-- ============================================================
-- se copia el personal existente al supertipo
-- ============================================================
-- direccion, fecha de contratacion, salario y nivel de acceso no existian en el
-- Proyecto 1: se cargan valores ficticios (la direccion queda sin registrar).

insert into personal (id_personal, tipo_personal, nombres, apellidos, dpi, telefono, direccion,
                      id_municipio, area, id_hospital, fecha_contratacion, salario, nivel_acceso)
select m.id_medico, 'medico', m.nombres, m.apellidos, m.dpi, m.telefono, 'Sin registrar',
       m.id_municipio, m.area, m.id_hospital,
       case when m.tipo_medico = 'externo' then null else date '2015-01-15' end,
       case m.tipo_medico when 'externo' then null
                          when 'especialista' then 18500.00
                          when 'general' then 13000.00
                          when 'residente' then 9500.00
                          else 6500.00 end,
       case when m.tipo_medico = 'externo' then 'consulta' else 'operativo' end
  from medico m;

insert into personal (id_personal, tipo_personal, nombres, apellidos, dpi, telefono, direccion,
                      id_municipio, area, id_hospital, fecha_contratacion, salario, nivel_acceso)
select e.id_enfermero, 'enfermero', e.nombres, e.apellidos, e.dpi, e.telefono, 'Sin registrar',
       h.id_municipio, 'Urbana', e.id_hospital,
       date '2016-03-01',
       case e.tipo when 'registrado' then 7200.00 else 3800.00 end,
       'operativo'
  from enfermero e
  join hospital h on h.id_hospital = e.id_hospital;

-- se copiaron ids hasta el 2005: el contador sigue en el 2006
--osea que el siguiente personal que se registre tendra id_personal = 2006 
-- ya que todo el personal existente se copio al supertipo, y los ids de medico y enfermero se conservaron y eran del 1 al 2005, entonces el siguiente id_personal que se genere sera 2006
alter table personal alter column id_personal restart with 2006;

-- ============================================================
-- subtipos: comparten la llave del supertipo
-- ============================================================

-- el id del subtipo ya no se genera solo: es el id_personal de la persona

--aqui quitamos la generacion automatica de id_medico porque ahora se genera en la tabla personal y se copia a medico y enfermero,
-- ya que el id_medico y id_enfermero son iguales al id_personal del supertipo
alter table medico alter column id_medico drop identity;
alter table enfermero alter column id_enfermero drop identity;


--aqui agregamos la columna tipo_personal a medico y enfermero, para que apunten al supertipo personal y asi poder hacer la herencia de tablas
--se añade la restriccion de que el tipo_personal de medico sea 'medico' y el de enfermero sea 'enfermero', para que no se pueda insertar un medico con tipo_personal = 'enfermero' o viceversa
alter table medico
    add column tipo_personal varchar(9) not null default 'medico',
    -- valida que la fila del subtipo medico apunte a personal de tipo medico
    add constraint ck_medico_tipo_personal check (tipo_personal = 'medico'), --aqui se valida que el tipo_personal de medico sea 'medico'
    add constraint fk_medico_personal foreign key (id_medico, tipo_personal)-- aqui se añade la restriccion de que el id_medico y tipo_personal de medico apunten a personal de tipo medico
        references personal(id_personal, tipo_personal)
        on delete cascade on update cascade;

alter table enfermero
    add column tipo_personal varchar(9) not null default 'enfermero',
    -- valida que la fila del subtipo enfermero apunte a personal de tipo enfermero
    add constraint ck_enfermero_tipo_personal check (tipo_personal = 'enfermero'),
    add constraint fk_enfermero_personal foreign key (id_enfermero, tipo_personal)
        references personal(id_personal, tipo_personal)
        on delete cascade on update cascade;

reset role;
