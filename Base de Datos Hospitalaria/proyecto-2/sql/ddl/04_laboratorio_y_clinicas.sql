-- Proyecto 2 - BD Hospitales de Occidente
-- 04_laboratorio_y_clinicas.sql : tablas que faltaban en consulta externa
--
-- El enunciado del Proyecto 1 pide registrar la clinica donde se atiende la
-- cita (hospital y numero de clinica) y las ordenes de laboratorio que el
-- medico da en la consulta. Se ejecuta sobre la base ya cargada: las clinicas
-- se crean a partir de las que ya aparecen en las citas.

set role admin;

-- clinicas (consultorios) de la unidad de consulta externa de cada hospital
create table clinica (
    id_clinica integer generated by default as identity primary key,
    id_unidad integer not null references unidad_medica(id_unidad)
        on delete restrict on update cascade,
    numero varchar(10) not null,
    -- no se repite el numero de clinica dentro de la misma unidad
    constraint uq_clinica_numero unique (id_unidad, numero)
);

-- una clinica por cada numero que ya se usaba en las citas, en la unidad de
-- consulta externa del hospital del medico
--osea que ponemos o agregamos a la tabla clinica los numeros de
-- clinica que ya se usaban en las citas, y los asociamos a la unidad de
-- consulta externa del hospital del medico que atendio la cita
insert into clinica (id_unidad, numero)
select distinct u.id_unidad, c.numero_clinica
from cita c
inner join medico m on m.id_medico = c.id_medico
inner join unidad_medica u on u.id_hospital = m.id_hospital and u.tipo_unidad = 'Consulta Externa'
order by u.id_unidad, c.numero_clinica;

-- cada cita apunta a su clinica --
--osea que ahora cada cita tendra un id_clinica que apunta a 
--la clinica donde se atendio la cita, y ese id_clinica se obtiene de la
-- tabla clinica, buscando la clinica que tiene el mismo numero de clinica y pertenece a 
--la unidad de consulta externa del hospital del medico que atendio la cita
alter table cita add column id_clinica integer references clinica(id_clinica)
    on delete restrict on update cascade;


--aqui pone a cada cita el id de su clinica correspondiente, buscando la clinica que 
--tiene el mismo numero de clinica y pertenece a la unidad de consulta externa del
--hospital del medico que atendio la cita
update cita c
set id_clinica = (select cl.id_clinica   
                  from clinica cl
                  inner join unidad_medica u on u.id_unidad = cl.id_unidad
                  inner join medico m on m.id_hospital = u.id_hospital
                  where m.id_medico = c.id_medico
                    and u.tipo_unidad = 'Consulta Externa'
                    and cl.numero = c.numero_clinica);

alter table cita alter column id_clinica set not null;--aqui ya pasa a ser obligatoria

-- catalogo de examenes de laboratorio que se pueden ordenar
create table examen_laboratorio (
    id_examen integer generated by default as identity primary key,
    nombre varchar(100) not null,
    descripcion varchar(200),
    costo numeric(10,2) not null,
    constraint uq_examen_nombre unique (nombre),
    -- el costo del examen no puede ser negativo
    constraint ck_examen_costo check (costo >= 0)
);

-- orden de laboratorio que el medico entrega en una consulta
create table orden_laboratorio (
    id_orden integer generated by default as identity primary key,
    id_consulta integer not null references consulta(id_consulta)
        on delete restrict on update cascade,
    fecha date not null,
    indicaciones text
);

-- examenes que lleva cada orden (una orden puede pedir varios examenes)
create table orden_examen (
    id_orden integer not null references orden_laboratorio(id_orden)
        on delete cascade on update cascade,
    id_examen integer not null references examen_laboratorio(id_examen)
        on delete restrict on update cascade,
    primary key (id_orden, id_examen)
);

reset role;
